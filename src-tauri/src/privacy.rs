//! Decides whether a clipboard change may be stored.
//!
//! Platform watchers translate the native clipboard into a [`ClipboardSnapshot`]:
//! the list of format names (UTIs on macOS, registered format names on Windows,
//! MIME types on Linux) plus the raw bytes of the few marker formats whose
//! *value* matters. Everything here is platform-independent and unit-tested.

use serde::Serialize;

/// macOS conventions from nspasteboard.org, used by 1Password, Bitwarden, KeePassXC, …
pub mod macos {
    pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
    pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
    pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
}

/// Windows clipboard formats registered by password managers and documented by
/// Microsoft for clipboard history / cloud clipboard.
pub mod windows {
    /// Presence alone means "do not monitor".
    pub const EXCLUDE_FROM_MONITOR: &str = "ExcludeClipboardContentFromMonitorProcessing";
    /// DWORD; 0 means "do not put into clipboard history".
    pub const CAN_INCLUDE_IN_HISTORY: &str = "CanIncludeInClipboardHistory";
    /// DWORD; 0 means "do not sync to cloud clipboard".
    pub const CAN_UPLOAD_TO_CLOUD: &str = "CanUploadToCloudClipboard";
    /// Formats whose data the watcher must read and pass on.
    pub const DATA_FORMATS: [&str; 2] = [CAN_INCLUDE_IN_HISTORY, CAN_UPLOAD_TO_CLOUD];
}

/// KDE convention (also set by KeePassXC on Linux).
pub mod linux {
    pub const PASSWORD_HINT: &str = "x-kde-passwordManagerHint";
    pub const PASSWORD_HINT_SECRET: &[u8] = b"secret";
    pub const DATA_FORMATS: [&str; 1] = [PASSWORD_HINT];
}

/// Known password managers, pre-filled in the exclusion list as a second line of
/// defense for apps that forget to set a concealed marker. Identifiers are the
/// macOS bundle id, the Windows executable and the Linux WM_CLASS respectively.
pub const DEFAULT_EXCLUDED_APPS: &[&str] = &[
    // macOS
    "com.1password.1password",
    "com.agilebits.onepassword7",
    "com.bitwarden.desktop",
    "org.keepassxc.keepassxc",
    "com.apple.keychainaccess",
    "com.apple.Passwords",
    // Windows
    "1Password.exe",
    "Bitwarden.exe",
    "KeePass.exe",
    "KeePassXC.exe",
    // Linux
    "1password",
    "bitwarden",
    "keepassxc",
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClipboardFormat {
    pub name: String,
    /// Only filled for marker formats listed in `windows::DATA_FORMATS` / `linux::DATA_FORMATS`.
    pub data: Option<Vec<u8>>,
}

impl ClipboardFormat {
    pub fn named(name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            data: None,
        }
    }
    pub fn with_data(name: impl Into<String>, data: impl Into<Vec<u8>>) -> Self {
        Self {
            name: name.into(),
            data: Some(data.into()),
        }
    }
}

/// The app that owned the clipboard / was frontmost when the copy happened.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceApp {
    /// Bundle id (macOS), executable name (Windows), WM_CLASS (X11).
    pub id: String,
    /// Human-readable name for the UI, if known.
    pub name: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ClipboardSnapshot {
    pub text: Option<String>,
    pub formats: Vec<ClipboardFormat>,
    pub source: Option<SourceApp>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum RejectReason {
    /// Marked confidential (password managers).
    Concealed,
    /// Marked as transient (e.g. drag & drop helpers, clipboard round-trips).
    Transient,
    /// Marked as auto-generated (e.g. TOTP codes copied by an app).
    AutoGenerated,
    /// Source app is on the user's exclusion list.
    ExcludedApp,
    /// No text representation (images/files arrive in a later phase).
    NoText,
}

fn has_format<'a>(formats: &'a [ClipboardFormat], name: &str) -> Option<&'a ClipboardFormat> {
    formats.iter().find(|f| f.name.eq_ignore_ascii_case(name))
}

/// A Windows DWORD marker that is present and equal to 0. Missing or malformed
/// data counts as "not set" (Windows' own default is "allowed").
fn dword_is_zero(format: Option<&ClipboardFormat>) -> bool {
    format
        .and_then(|f| f.data.as_deref())
        .and_then(|d| d.get(..4))
        .is_some_and(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]) == 0)
}

/// Checks the confidentiality markers of all platforms. Markers from "foreign"
/// platforms are harmless to check (they simply never appear there) and keep
/// this function testable everywhere.
pub fn marker_verdict(formats: &[ClipboardFormat]) -> Option<RejectReason> {
    // macOS
    if has_format(formats, macos::CONCEALED).is_some() {
        return Some(RejectReason::Concealed);
    }
    if has_format(formats, macos::TRANSIENT).is_some() {
        return Some(RejectReason::Transient);
    }
    if has_format(formats, macos::AUTO_GENERATED).is_some() {
        return Some(RejectReason::AutoGenerated);
    }

    // Windows
    if has_format(formats, windows::EXCLUDE_FROM_MONITOR).is_some()
        || dword_is_zero(has_format(formats, windows::CAN_INCLUDE_IN_HISTORY))
        || dword_is_zero(has_format(formats, windows::CAN_UPLOAD_TO_CLOUD))
    {
        return Some(RejectReason::Concealed);
    }

    // Linux (KDE / KeePassXC)
    if let Some(hint) = has_format(formats, linux::PASSWORD_HINT) {
        let secret = hint.data.as_deref().is_some_and(|d| {
            d.trim_ascii()
                .eq_ignore_ascii_case(linux::PASSWORD_HINT_SECRET)
        });
        if secret {
            return Some(RejectReason::Concealed);
        }
    }
    None
}

/// Case-insensitive match against id or display name; a trailing ".exe" is
/// optional on either side so "KeePassXC" also excludes "KeePassXC.exe".
pub fn is_excluded(source: &SourceApp, excluded: &[String]) -> bool {
    fn norm(s: &str) -> String {
        let s = s.trim().to_lowercase();
        s.strip_suffix(".exe").map(str::to_owned).unwrap_or(s)
    }
    let candidates: Vec<String> = std::iter::once(source.id.as_str())
        .chain(source.name.as_deref())
        .map(norm)
        .collect();
    excluded
        .iter()
        .map(|e| norm(e))
        .filter(|e| !e.is_empty())
        .any(|e| candidates.contains(&e))
}

/// Full privacy check for one clipboard change.
pub fn evaluate(
    snapshot: &ClipboardSnapshot,
    excluded_apps: &[String],
) -> Result<(), RejectReason> {
    if let Some(reason) = marker_verdict(&snapshot.formats) {
        return Err(reason);
    }
    if snapshot
        .source
        .as_ref()
        .is_some_and(|s| is_excluded(s, excluded_apps))
    {
        return Err(RejectReason::ExcludedApp);
    }
    if snapshot.text.is_none() {
        return Err(RejectReason::NoText);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn snap(text: &str, formats: Vec<ClipboardFormat>) -> ClipboardSnapshot {
        ClipboardSnapshot {
            text: Some(text.into()),
            formats,
            source: None,
        }
    }

    fn excluded(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn plain_text_is_accepted() {
        let s = snap(
            "hello",
            vec![ClipboardFormat::named("public.utf8-plain-text")],
        );
        assert_eq!(evaluate(&s, &[]), Ok(()));
    }

    #[test]
    fn macos_markers() {
        for (marker, reason) in [
            (macos::CONCEALED, RejectReason::Concealed),
            (macos::TRANSIENT, RejectReason::Transient),
            (macos::AUTO_GENERATED, RejectReason::AutoGenerated),
        ] {
            let s = snap(
                "pw",
                vec![
                    ClipboardFormat::named("public.utf8-plain-text"),
                    ClipboardFormat::named(marker),
                ],
            );
            assert_eq!(evaluate(&s, &[]), Err(reason), "{marker}");
        }
    }

    #[test]
    fn concealed_wins_over_transient() {
        let s = snap(
            "pw",
            vec![
                ClipboardFormat::named(macos::TRANSIENT),
                ClipboardFormat::named(macos::CONCEALED),
            ],
        );
        assert_eq!(evaluate(&s, &[]), Err(RejectReason::Concealed));
    }

    #[test]
    fn windows_exclude_format_presence_is_enough() {
        let s = snap(
            "pw",
            vec![ClipboardFormat::named(windows::EXCLUDE_FROM_MONITOR)],
        );
        assert_eq!(evaluate(&s, &[]), Err(RejectReason::Concealed));
    }

    #[test]
    fn windows_dword_markers_respect_value() {
        let zero = 0u32.to_le_bytes();
        let one = 1u32.to_le_bytes();
        for name in [
            windows::CAN_INCLUDE_IN_HISTORY,
            windows::CAN_UPLOAD_TO_CLOUD,
        ] {
            let rejected = snap("pw", vec![ClipboardFormat::with_data(name, zero)]);
            assert_eq!(
                evaluate(&rejected, &[]),
                Err(RejectReason::Concealed),
                "{name}=0"
            );
            let allowed = snap("pw", vec![ClipboardFormat::with_data(name, one)]);
            assert_eq!(evaluate(&allowed, &[]), Ok(()), "{name}=1");
        }
    }

    #[test]
    fn windows_dword_without_data_is_not_a_verdict() {
        // Truncated or unreadable data must not hide normal copies.
        let s = snap(
            "x",
            vec![
                ClipboardFormat::named(windows::CAN_INCLUDE_IN_HISTORY),
                ClipboardFormat::with_data(windows::CAN_UPLOAD_TO_CLOUD, vec![0, 0]),
            ],
        );
        assert_eq!(evaluate(&s, &[]), Ok(()));
    }

    #[test]
    fn kde_password_hint() {
        let secret = snap(
            "pw",
            vec![ClipboardFormat::with_data(
                linux::PASSWORD_HINT,
                b"secret\n".to_vec(),
            )],
        );
        assert_eq!(evaluate(&secret, &[]), Err(RejectReason::Concealed));
        let other = snap(
            "x",
            vec![ClipboardFormat::with_data(
                linux::PASSWORD_HINT,
                b"public".to_vec(),
            )],
        );
        assert_eq!(evaluate(&other, &[]), Ok(()));
    }

    #[test]
    fn format_names_match_case_insensitively() {
        let s = snap(
            "pw",
            vec![ClipboardFormat::named("ORG.NSPASTEBOARD.CONCEALEDTYPE")],
        );
        assert_eq!(evaluate(&s, &[]), Err(RejectReason::Concealed));
    }

    #[test]
    fn excluded_apps_match_id_or_name_with_optional_exe() {
        let list = excluded(&["KeePassXC", "com.bitwarden.desktop", "  "]);
        let by_exe = SourceApp {
            id: "keepassxc.exe".into(),
            name: None,
        };
        let by_bundle = SourceApp {
            id: "com.bitwarden.desktop".into(),
            name: Some("Bitwarden".into()),
        };
        let by_name = SourceApp {
            id: "org.example".into(),
            name: Some("keepassxc".into()),
        };
        let other = SourceApp {
            id: "com.apple.Safari".into(),
            name: Some("Safari".into()),
        };
        assert!(is_excluded(&by_exe, &list));
        assert!(is_excluded(&by_bundle, &list));
        assert!(is_excluded(&by_name, &list));
        assert!(!is_excluded(&other, &list));
    }

    #[test]
    fn excluded_source_is_rejected() {
        let mut s = snap("x", vec![]);
        s.source = Some(SourceApp {
            id: "Bitwarden.exe".into(),
            name: None,
        });
        let defaults: Vec<String> = DEFAULT_EXCLUDED_APPS
            .iter()
            .map(|s| s.to_string())
            .collect();
        assert_eq!(evaluate(&s, &defaults), Err(RejectReason::ExcludedApp));
    }

    #[test]
    fn missing_text_is_rejected() {
        let s = ClipboardSnapshot {
            text: None,
            formats: vec![ClipboardFormat::named("public.png")],
            source: None,
        };
        assert_eq!(evaluate(&s, &[]), Err(RejectReason::NoText));
    }
}
